"""Generate RESULTS.md and results/summary.json from the result files.

Verdict logic implements the thresholds pre-registered in HYPOTHESES.md.
RESULTS.md is generated, never hand typed.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

REPO_ROOT = Path(__file__).resolve().parent.parent
RESULTS_DIR = REPO_ROOT / "results"


def load(name):
    path = RESULTS_DIR / name
    if not path.exists():
        return None
    return json.loads(path.read_text(encoding="utf-8"))


def verdict_h1(data):
    if data is None:
        return "Not yet measured"
    if data["mismatches"] == [] and data["match_rate"] == 1.0:
        return "Supported"
    if data["match_rate"] >= 0.90:
        return "Partially supported"
    return "Refuted"


def verdict_h2(data):
    if data is None:
        return "Not yet measured"
    counts = [eng["runs_matching_run1"] for eng in data["per_engine"].values()]
    if all(c >= 19 for c in counts):
        return "Supported"
    if all(c >= 16 for c in counts):
        return "Partially supported"
    return "Refuted"


def verdict_h3(data):
    if data is None:
        return "Not yet measured"
    if data["recall"] >= 0.90:
        return "Supported"
    if data["recall"] >= 0.70:
        return "Partially supported"
    return "Refuted"


def verdict_h4(data):
    if data is None:
        return "Not yet measured"
    if data["precision"] >= 0.90 and data["recall"] >= 0.90:
        return "Supported"
    if data["precision"] >= 0.75 and data["recall"] >= 0.75:
        return "Partially supported"
    return "Refuted"


def main() -> int:
    rq1_eq = load("rq1_plan_equivalence.json")
    rq1_rep = load("rq1_reproducibility.json")
    rq2 = load("rq2_drift.json")
    rq3 = load("rq3_policy.json")
    verdicts = {
        "H1_plan_equivalence": verdict_h1(rq1_eq),
        "H2_rebuild_reproducibility": verdict_h2(rq1_rep),
        "H3_drift_recall": verdict_h3(rq2),
        "H4_policy_precision_recall": verdict_h4(rq3),
    }
    summary = {"verdicts": verdicts}
    if rq1_eq:
        summary["rq1_plan"] = {"matches": rq1_eq["matches"],
                               "compared": rq1_eq["addresses_compared"],
                               "match_rate": rq1_eq["match_rate"]}
    if rq1_rep:
        summary["rq1_reproducibility"] = {
            name: {"matching": eng["runs_matching_run1"], "total": eng["runs_total"],
                   "median_seconds": eng["median_seconds"]}
            for name, eng in rq1_rep["per_engine"].items()}
    if rq2:
        summary["rq2_drift"] = {"detected": rq2["detected"], "total": rq2["trials_total"],
                                "recall": rq2["recall"],
                                "recall_managed_only": rq2["recall_managed_only"],
                                "misses_by_type": rq2["misses_by_type"]}
    if rq3:
        summary["rq3_policy"] = {"tp": rq3["true_positives"], "fp": rq3["false_positives"],
                                  "tn": rq3["true_negatives"], "fn": rq3["false_negatives"],
                                  "precision": rq3["precision"], "recall": rq3["recall"]}
    (RESULTS_DIR / "summary.json").write_text(
        json.dumps(summary, indent=2, sort_keys=True) + "\n", encoding="utf-8")

    lines = []
    lines.append("# RESULTS")
    lines.append("")
    lines.append("Generated by harness/generate_results_md.py from the files in results/. Do not edit by hand.")
    lines.append("")
    lines.append("## Verdicts")
    lines.append("")
    lines.append("| Hypothesis | Verdict |")
    lines.append("| --- | --- |")
    for key, value in verdicts.items():
        lines.append(f"| {key} | {value} |")
    lines.append("")
    lines.append("## RQ1 plan equivalence")
    lines.append("")
    if rq1_eq:
        lines.append(f"- Engines: OpenTofu ({rq1_eq['engine_versions'].get('tofu', 'unknown')}) and Terraform ({rq1_eq['engine_versions'].get('terraform', 'unknown')}).")
        lines.append(f"- Addresses compared: {rq1_eq['addresses_compared']}. Matches: {rq1_eq['matches']}. Match rate: {rq1_eq['match_rate']:.4f}.")
        lines.append(f"- Mismatches: {len(rq1_eq['mismatches'])}.")
        for item in rq1_eq["mismatches"]:
            lines.append(f"  - {item['address']}: tofu={item['tofu']} terraform={item['terraform']}")
    else:
        lines.append("- Not yet measured.")
    lines.append("")
    lines.append("## RQ1 rebuild reproducibility, 20 runs per engine")
    lines.append("")
    if rq1_rep:
        lines.append("| Engine | Version | Runs matching run 1 | Median seconds |")
        lines.append("| --- | --- | --- | --- |")
        for name, eng in rq1_rep["per_engine"].items():
            lines.append(f"| {name} | {eng['version']} | {eng['runs_matching_run1']} of {eng['runs_total']} | {eng['median_seconds']} |")
    else:
        lines.append("- Not yet measured.")
    lines.append("")
    lines.append("## RQ2 drift detection")
    lines.append("")
    if rq2:
        lines.append(f"- Engine: OpenTofu ({rq2['engine_version']}). Trials: {rq2['trials_total']}. Detected: {rq2['detected']}. Recall: {rq2['recall']:.4f}.")
        lines.append(f"- Recall over managed file mutations only: {rq2['recall_managed_only']:.4f} ({rq2['managed_detected']} of {rq2['managed_trials']}).")
        lines.append(f"- Naive file exists baseline recall: {rq2['naive_exists_recall']:.4f} ({rq2['naive_exists_detected']} of {rq2['trials_total']}).")
        lines.append("- Misses by type:")
        for kind, count in sorted(rq2["misses_by_type"].items()):
            lines.append(f"  - {kind}: {count}")
    else:
        lines.append("- Not yet measured.")
    lines.append("")
    lines.append("## RQ3 policy precision and recall")
    lines.append("")
    if rq3:
        lines.append(f"- Tool: conftest ({rq3['tool_version']}). Corpus: {rq3['corpus_total']} files.")
        lines.append(f"- True positives: {rq3['true_positives']}. False positives: {rq3['false_positives']}. True negatives: {rq3['true_negatives']}. False negatives: {rq3['false_negatives']}.")
        lines.append(f"- Precision: {rq3['precision']:.4f}. Recall: {rq3['recall']:.4f}.")
        lines.append("- False negatives:")
        for record in rq3["records"]:
            if record["outcome"] == "false_negative":
                lines.append(f"  - {record['file']} ({record['violation_type']})")
        lines.append("- False positives:")
        fps = [r for r in rq3["records"] if r["outcome"] == "false_positive"]
        if fps:
            for record in fps:
                lines.append(f"  - {record['file']}")
        else:
            lines.append("  - none")
    else:
        lines.append("- Not yet measured.")
    lines.append("")
    (REPO_ROOT / "RESULTS.md").write_text("\n".join(lines), encoding="utf-8")
    print("wrote RESULTS.md and results/summary.json")
    print(json.dumps(verdicts, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
